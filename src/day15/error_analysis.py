def load_latest_predictions(
    predictions_path: str | Path | None = None,
) -> pd.DataFrame:
    """
    Load predictions from a specified CSV or the latest Day 14 run.

    Parameters
    ----------
    predictions_path:
        Optional path to a prediction CSV.

    Returns
    -------
    pandas.DataFrame
        Loaded prediction records.

    Raises
    ------
    FileNotFoundError
        If no suitable prediction file exists.
    """

    if predictions_path is not None:
        path = Path(predictions_path)

        if not path.is_absolute():
            path = PROJECT_ROOT / path

        if not path.is_file():
            raise FileNotFoundError(
                f"Prediction file does not exist: {path}"
            )

        return pd.read_csv(path)

    if not DAY14_REPORT_DIR.exists():
        raise FileNotFoundError(
            f"Day 14 report directory does not exist: "
            f"{DAY14_REPORT_DIR}"
        )

    prediction_files = list(
        DAY14_REPORT_DIR.glob("*_predictions.csv")
    )

    if not prediction_files:
        raise FileNotFoundError(
            "No Day 14 prediction CSV files were found in "
            f"{DAY14_REPORT_DIR}"
        )

    latest_file = max(
        prediction_files,
        key=lambda file: file.stat().st_mtime,
    )

    print(f"Loading predictions: {latest_file.name}")

    return pd.read_csv(latest_file)


