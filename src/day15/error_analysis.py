# 7. TEMPORAL ERROR ANALYSIS
# ============================================================

def build_temporal_analysis(
    dataframe: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Calculate performance by hour of day and day of week.

    Missing predictions remain part of the total group size
    but are excluded from error metrics.
    """

    temporal = dataframe.copy()

    temporal["hour"] = temporal[
        "timestamp"
    ].dt.hour

    temporal["day_of_week"] = temporal[
        "timestamp"
    ].dt.day_name()

    hourly_rows = []

    for (model, hour), group in temporal.groupby(
        ["model", "hour"],
        sort=True,
    ):
        metrics = calculate_metrics(
            group["actual"],
            group["predicted"],
        )

        hourly_rows.append(
            {
                "model": str(model),
                "hour": int(hour),
                "observations": int(
                    metrics["valid_predictions"]
                ),
                "validation_rows": int(len(group)),
                "mae": metrics["mae"],
                "rmse": metrics["rmse"],
                "bias": metrics["bias"],
            }
        )

    hourly = pd.DataFrame(
        hourly_rows,
        columns=[
            "model",
            "hour",
            "observations",
            "validation_rows",
            "mae",
            "rmse",
            "bias",
        ],
    )

    day_order = [
        "Monday",
        "Tuesday",
        "Wednesday",
        "Thursday",
        "Friday",
        "Saturday",
        "Sunday",
    ]

    daily_rows = []

    for (model, day), group in temporal.groupby(
        ["model", "day_of_week"],
        sort=False,
    ):
        metrics = calculate_metrics(
            group["actual"],
            group["predicted"],
        )

        daily_rows.append(
            {
                "model": str(model),
                "day_of_week": str(day),
                "observations": int(
                    metrics["valid_predictions"]
                ),
                "validation_rows": int(len(group)),
                "mae": metrics["mae"],
                "rmse": metrics["rmse"],
                "bias": metrics["bias"],
            }
        )

    daily = pd.DataFrame(
        daily_rows,
        columns=[
            "model",
            "day_of_week",
            "observations",
            "validation_rows",
            "mae",
            "rmse",
            "bias",
        ],
    )

    if not daily.empty:
        daily["day_of_week"] = pd.Categorical(
            daily["day_of_week"],
            categories=day_order,
            ordered=True,
        )

        daily = (
            daily.sort_values(
                ["model", "day_of_week"]
            )
            .reset_index(drop=True)
        )

    return hourly, daily


