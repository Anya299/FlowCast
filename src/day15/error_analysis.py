# 3. DATA VALIDATION
# ============================================================

def validate_predictions(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Validate prediction records and normalize data types.

    Missing predictions are permitted because a forecasting
    strategy may lack the historical observation it requires.

    Actual target values must not be missing.

    Duplicate road/timestamp/model records are rejected.
    """

    if not isinstance(dataframe, pd.DataFrame):
        raise TypeError(
            "Input must be a pandas DataFrame."
        )

    if dataframe.empty:
        raise ValueError(
            "Prediction DataFrame must not be empty."
        )

    missing_columns = REQUIRED_COLUMNS - set(
        dataframe.columns
    )

    if missing_columns:
        raise ValueError(
            "Missing required columns: "
            + ", ".join(sorted(missing_columns))
        )

    result = dataframe.copy()

    result["road_id"] = (
        result["road_id"].astype("string").str.strip()
    )

    result["model"] = (
        result["model"].astype("string").str.strip()
    )

    if result["road_id"].isna().any():
        raise ValueError(
            "road_id must not contain missing values."
        )

    if result["model"].isna().any():
        raise ValueError(
            "model must not contain missing values."
        )

    if result["road_id"].eq("").any():
        raise ValueError(
            "road_id must not contain empty strings."
        )

    if result["model"].eq("").any():
        raise ValueError(
            "model must not contain empty strings."
        )

    # Normalize timestamps.
    for column in (
        "timestamp",
        "reference_timestamp",
    ):
        result[column] = pd.to_datetime(
            result[column],
            errors="raise",
        )

    # Convert numerical columns.
    for column in ("actual", "predicted"):
        result[column] = pd.to_numeric(
            result[column],
            errors="raise",
        )

    # Infinite values should not be accepted as real measurements.
    actual_values = result["actual"].to_numpy(
        dtype=float,
        na_value=np.nan,
    )

    if not np.isfinite(actual_values).all():
        raise ValueError(
            "Actual values must be finite and non-missing."
        )

    predicted_values = result["predicted"].to_numpy(
        dtype=float,
        na_value=np.nan,
    )

    if np.isinf(predicted_values).any():
        raise ValueError(
            "Predictions may be missing but must not be infinite."
        )

    # Each road, target timestamp, and model must occur once.
    duplicate_columns = [
        "road_id",
        "timestamp",
        "model",
    ]

    duplicate_mask = result.duplicated(
        subset=duplicate_columns,
        keep=False,
    )

    if duplicate_mask.any():
        duplicate_count = int(duplicate_mask.sum())

        raise ValueError(
            f"Found {duplicate_count} records participating "
            "in duplicate road/timestamp/model combinations."
        )

    return result.reset_index(drop=True)


# ============================================================
# 4. FORECAST METRICS
# ============================================================

def calculate_metrics(
    actual: pd.Series,
    predicted: pd.Series,
) -> dict[str, float | int]:
    """
    Calculate forecasting metrics using valid prediction pairs.

    Missing predictions are excluded from the calculation.

    Bias is defined as:

        mean(predicted - actual)

    Positive bias indicates overprediction.
    Negative bias indicates underprediction.
    """

    actual_series = pd.Series(
        actual
    ).reset_index(drop=True)

    predicted_series = pd.Series(
        predicted
    ).reset_index(drop=True)

    if len(actual_series) != len(predicted_series):
        raise ValueError(
            "Actual and predicted series must have equal lengths."
        )

    actual_values = pd.to_numeric(
        actual_series,
        errors="raise",
    ).to_numpy(dtype=float, na_value=np.nan)

    predicted_values = pd.to_numeric(
        predicted_series,
        errors="raise",
    ).to_numpy(dtype=float, na_value=np.nan)

    if not np.isfinite(actual_values).all():
        raise ValueError(
            "Actual values must be finite and non-missing."
        )

    if np.isinf(predicted_values).any():
        raise ValueError(
            "Predictions must not contain infinite values."
        )

    valid_mask = np.isfinite(predicted_values)

    valid_actual = actual_values[valid_mask]

    valid_predicted = predicted_values[valid_mask]

    valid_count = int(valid_mask.sum())

    if valid_count == 0:
        return {
            "valid_predictions": 0,
            "mae": float("nan"),
            "rmse": float("nan"),
            "bias": float("nan"),
        }

    errors = valid_predicted - valid_actual

    mae = float(
        np.mean(np.abs(errors))
    )

    rmse = float(
        np.sqrt(np.mean(np.square(errors)))
    )

    bias = float(
        np.mean(errors)
    )

    return {
        "valid_predictions": valid_count,
        "mae": mae,
        "rmse": rmse,
        "bias": bias,
    }


