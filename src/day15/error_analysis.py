# 5. COMMON-POPULATION MODEL COMPARISON
# ============================================================

def build_common_population_comparison(
    dataframe: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Compare forecasting strategies on identical observations.

    An observation belongs to the common population only when
    both expected models have valid predictions for that
    road and target timestamp.

    Returns
    -------
    comparison:
        One row per model with common-population metrics.

    common:
        Paired observations containing actual values and both
        models' predictions.
    """

    required_models = EXPECTED_MODELS

    available_models = set(
        dataframe["model"].dropna().astype(str)
    )

    missing_models = required_models - available_models

    if missing_models:
        raise ValueError(
            "Missing expected forecasting models: "
            + ", ".join(sorted(missing_models))
        )

    selected = dataframe.loc[
        dataframe["model"].isin(required_models),
        [
            "road_id",
            "timestamp",
            "actual",
            "predicted",
            "model",
        ],
    ].copy()

    # Every model must agree on the actual target for a
    # given road and timestamp.
    actual_counts = (
        selected.groupby(
            ["road_id", "timestamp"]
        )["actual"]
        .nunique()
    )

    if (actual_counts > 1).any():
        raise ValueError(
            "Actual values differ between models for the "
            "same road/timestamp observation."
        )

    selected["model"] = selected["model"].astype(str)

    pivoted = selected.pivot(
        index=["road_id", "timestamp"],
        columns="model",
        values="predicted",
    )

    pivoted = pivoted.reset_index()

    actual_lookup = (
        selected[
            ["road_id", "timestamp", "actual"]
        ]
        .drop_duplicates(
            subset=["road_id", "timestamp"]
        )
    )

    common = pivoted.merge(
        actual_lookup,
        on=["road_id", "timestamp"],
        how="left",
        validate="one_to_one",
    )

    for model in sorted(required_models):
        if model not in common.columns:
            common[model] = np.nan

    common = common[
        [
            "road_id",
            "timestamp",
            "actual",
            "naive_30min",
            "seasonal_naive_24h",
        ]
    ]

    common_mask = (
        common["naive_30min"].notna()
        & common["seasonal_naive_24h"].notna()
    )

    common = (
        common.loc[common_mask]
        .reset_index(drop=True)
    )

    total_observations = (
        dataframe.groupby("model")["timestamp"].size()
    )

    common_count = len(common)

    comparison_rows = []

    for model in sorted(required_models):
        model_records = dataframe.loc[
            dataframe["model"] == model
        ]

        total_count = int(
            total_observations.get(model, 0)
        )

        metrics = calculate_metrics(
            common["actual"],
            common[model],
        )

        coverage_pct = (
            common_count / total_count * 100.0
            if total_count
            else 0.0
        )

        comparison_rows.append(
            {
                "model": model,
                "total_validation_observations": total_count,
                "common_valid_observations": common_count,
                "common_population_coverage_pct": coverage_pct,
                "mae": metrics["mae"],
                "rmse": metrics["rmse"],
                "bias": metrics["bias"],
            }
        )

    comparison = pd.DataFrame(
        comparison_rows
    )

    return comparison, common


