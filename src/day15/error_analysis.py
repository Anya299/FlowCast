def save_common_population_figures(
    comparison: pd.DataFrame,
    road_analysis: pd.DataFrame,
    hourly: pd.DataFrame,
) -> None:
    """
    Generate the four Day 15 diagnostic figures.
    """

    FIGURES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # Figure 1: Common-population MAE
    # --------------------------------------------------------

    mae_data = comparison.dropna(
        subset=["mae"]
    )

    figure, axis = plt.subplots(
        figsize=(9, 5)
    )

    axis.bar(
        mae_data["model"],
        mae_data["mae"],
    )

    axis.set_title(
        "FlowCast — Common-Population MAE"
    )

    axis.set_ylabel(
        "Mean Absolute Error"
    )

    axis.set_xlabel(
        "Forecasting Strategy"
    )

    axis.tick_params(
        axis="x",
        rotation=10,
    )

    axis.grid(
        axis="y",
        alpha=0.25,
    )

    figure.tight_layout()

    figure.savefig(
        FIGURES_DIR / "common_population_mae.png",
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(figure)

    # --------------------------------------------------------
    # Figure 2: Common-population RMSE
    # --------------------------------------------------------

    rmse_data = comparison.dropna(
        subset=["rmse"]
    )

    figure, axis = plt.subplots(
        figsize=(9, 5)
    )

    axis.bar(
        rmse_data["model"],
        rmse_data["rmse"],
    )

    axis.set_title(
        "FlowCast — Common-Population RMSE"
    )

    axis.set_ylabel(
        "Root Mean Squared Error"
    )

    axis.set_xlabel(
        "Forecasting Strategy"
    )

    axis.tick_params(
        axis="x",
        rotation=10,
    )

    axis.grid(
        axis="y",
        alpha=0.25,
    )

    figure.tight_layout()

    figure.savefig(
        FIGURES_DIR / "common_population_rmse.png",
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(figure)

    # --------------------------------------------------------
    # Figure 3: MAE by hour
    # --------------------------------------------------------

    figure, axis = plt.subplots(
        figsize=(11, 6)
    )

    for model, group in hourly.groupby(
        "model",
        sort=True,
    ):
        axis.plot(
            group["hour"],
            group["mae"],
            marker="o",
            linewidth=1.8,
            label=MODEL_LABELS.get(model, model),
        )

    axis.set_title(
        "FlowCast — Forecast MAE by Hour of Day"
    )

    axis.set_xlabel(
        "Hour of Day"
    )

    axis.set_ylabel(
        "Mean Absolute Error"
    )

    axis.set_xticks(
        range(24)
    )

    axis.grid(
        alpha=0.25,
    )

    axis.legend()

    figure.tight_layout()

    figure.savefig(
        FIGURES_DIR / "mae_by_hour.png",
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(figure)

    # --------------------------------------------------------
    # Figure 4: Prediction coverage by road
    # --------------------------------------------------------

    if not road_analysis.empty:
        coverage = road_analysis.pivot(
            index="road_id",
            columns="model",
            values="coverage_pct",
        )

        figure, axis = plt.subplots(
            figsize=(12, 7)
        )

        coverage.plot(
            kind="bar",
            ax=axis,
        )

        axis.set_title(
            "FlowCast — Prediction Coverage by Road"
        )

        axis.set_xlabel(
            "Road ID"
        )

        axis.set_ylabel(
            "Prediction Coverage (%)"
        )

        axis.tick_params(
            axis="x",
            rotation=45,
        )

        axis.grid(
            axis="y",
            alpha=0.25,
        )

        axis.legend(
            title="Forecasting Strategy"
        )

        figure.tight_layout()

        figure.savefig(
            FIGURES_DIR / "prediction_coverage_by_road.png",
            dpi=180,
            bbox_inches="tight",
        )

        plt.close(figure)


