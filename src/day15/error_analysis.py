def run_analysis(
    predictions_path: str | Path | None = None,
) -> dict[str, object]:
    """
    Execute the complete Day 15 analysis pipeline.

    Returns a dictionary containing the generated analysis
    tables and report path.
    """

    DAY15_REPORT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    FIGURES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("=" * 65)
    print("FLOWCAST DAY 15 — ERROR ANALYSIS")
    print("=" * 65)

    # Step 1: Load and validate.
    raw_predictions = load_latest_predictions(
        predictions_path
    )

    predictions = validate_predictions(
        raw_predictions
    )

    print(
        f"\nValidated prediction records: "
        f"{len(predictions):,}"
    )

    print(
        f"Unique roads: "
        f"{predictions['road_id'].nunique()}"
    )

    print(
        f"Models: "
        f"{sorted(predictions['model'].unique().tolist())}"
    )

    # Step 2: Common-population comparison.
    comparison, common = (
        build_common_population_comparison(
            predictions
        )
    )

    comparison_path = (
        DAY15_REPORT_DIR
        / "common_population_comparison.csv"
    )

    comparison.to_csv(
        comparison_path,
        index=False,
    )

    # Store paired observations for reproducibility.
    common_path = (
        DAY15_REPORT_DIR
        / "common_population_observations.csv"
    )

    common.to_csv(
        common_path,
        index=False,
    )

    # Step 3: Road-level performance.
    road_analysis = build_road_analysis(
        predictions
    )

    road_path = (
        DAY15_REPORT_DIR
        / "road_level_performance.csv"
    )

    road_analysis.to_csv(
        road_path,
        index=False,
    )

    # Step 4: Temporal analysis.
    hourly, daily = build_temporal_analysis(
        predictions
    )

    hourly_path = (
        DAY15_REPORT_DIR
        / "hourly_error_analysis.csv"
    )

    daily_path = (
        DAY15_REPORT_DIR
        / "day_of_week_error_analysis.csv"
    )

    hourly.to_csv(
        hourly_path,
        index=False,
    )

    daily.to_csv(
        daily_path,
        index=False,
    )

    # Step 5: Figures.
    save_common_population_figures(
        comparison,
        road_analysis,
        hourly,
    )

    # Step 6: Main Markdown report.
    report_path = generate_markdown_report(
        comparison=comparison,
        road_analysis=road_analysis,
        hourly=hourly,
        daily=daily,
        total_observations=len(predictions),
        common_observations=len(common),
    )

    # Step 7: Reproducibility metadata.
    metadata = {
        "project": "FlowCast",
        "day": 15,
        "analysis": "Forecast Error Analysis",
        "generated_at_utc": datetime.now(
            timezone.utc
        ).isoformat(),
        "input_records": int(len(predictions)),
        "unique_roads": int(
            predictions["road_id"].nunique()
        ),
        "models": sorted(
            predictions["model"].unique().tolist()
        ),
        "common_valid_observations": int(
            len(common)
        ),
        "outputs": [
            "common_population_comparison.csv",
            "common_population_observations.csv",
            "road_level_performance.csv",
            "hourly_error_analysis.csv",
            "day_of_week_error_analysis.csv",
            "day15_error_analysis_report.md",
            "figures/common_population_mae.png",
            "figures/common_population_rmse.png",
            "figures/mae_by_hour.png",
            "figures/prediction_coverage_by_road.png",
        ],
    }

    metadata_path = (
        DAY15_REPORT_DIR
        / "day15_metadata.json"
    )

    metadata_path.write_text(
        json.dumps(
            metadata,
            indent=4,
        ),
        encoding="utf-8",
    )

    # Step 8: Display key results.
    print("\nCOMMON-POPULATION COMPARISON")
    print("-" * 65)

    print(
        comparison.to_string(
            index=False,
            float_format=lambda value: f"{value:.4f}",
        )
    )

    print("\nROAD-LEVEL PERFORMANCE — HIGHEST MAE")
    print("-" * 65)

    print(
        road_analysis.head(10).to_string(
            index=False,
            float_format=lambda value: f"{value:.4f}",
        )
    )

    print("\nHOURLY ERROR ANALYSIS — FIRST TEN ROWS")
    print("-" * 65)

    print(
        hourly.head(10).to_string(
            index=False,
            float_format=lambda value: f"{value:.4f}",
        )
    )

    print("\nOUTPUT FILES")
    print("-" * 65)

    for output in (
        comparison_path,
        common_path,
        road_path,
        hourly_path,
        daily_path,
        report_path,
        metadata_path,
    ):
        print(output.relative_to(PROJECT_ROOT))

    print(
        "reports/day15/figures/"
    )

    print("\nFLOWCAST DAY 15 — ANALYSIS COMPLETE")

    return {
        "predictions": predictions,
        "comparison": comparison,
        "common_observations": common,
        "road_analysis": road_analysis,
        "hourly_analysis": hourly,
        "daily_analysis": daily,
        "report_path": report_path,
        "metadata_path": metadata_path,
    }


# ============================================================
# 11. ENTRY POINT
# ============================================================

if __name__ == "__main__":
    run_analysis()