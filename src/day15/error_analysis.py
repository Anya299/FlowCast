# 6. ROAD-LEVEL PERFORMANCE ANALYSIS
# ============================================================

def build_road_analysis(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Calculate forecasting accuracy and prediction coverage
    independently for each road and model.
    """

    rows = []

    for (road_id, model), group in dataframe.groupby(
        ["road_id", "model"],
        sort=True,
    ):
        total_rows = len(group)

        metrics = calculate_metrics(
            group["actual"],
            group["predicted"],
        )

        valid_count = int(
            metrics["valid_predictions"]
        )

        missing_count = total_rows - valid_count

        coverage_pct = (
            valid_count / total_rows * 100.0
            if total_rows
            else 0.0
        )

        rows.append(
            {
                "road_id": str(road_id),
                "model": str(model),
                "validation_rows": int(total_rows),
                "valid_predictions": valid_count,
                "missing_predictions": int(missing_count),
                "coverage_pct": float(coverage_pct),
                "mae": metrics["mae"],
                "rmse": metrics["rmse"],
                "bias": metrics["bias"],
            }
        )

    result = pd.DataFrame(rows)

    if not result.empty:
        result = result.sort_values(
            ["model", "mae", "road_id"],
            ascending=[True, False, True],
            na_position="last",
        ).reset_index(drop=True)

    return result


